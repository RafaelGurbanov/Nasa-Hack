"""
Build a small real elevation map of Gale crater (where NASA's Curiosity rover landed)
for the 3D view, from NASA's Mars Orbiter Laser Altimeter (MOLA) global grid.

Source data (not stored in this repo, 33 MB):
  MOLA Mission Experiment Gridded Data Record, 16 pixels/degree, DATA_SET_ID MGS-M-MOLA-5-MEGDR-L3-V1.0
  https://pds-geosciences.wustl.edu/mgs/mgs-m-mola-5-megdr-l3-v1/mgsl_300x/meg016/megt90n000eb.img (+ .lbl)
  Producer: MGS MOLA Science Team (D. E. Smith, NASA Goddard Space Flight Center), via the NASA PDS Geosciences Node.

Usage:
  python data/build_gale_heightmap.py path/to/megt90n000eb.img
Writes data/gale_heightmap.js (64 x 64 heights in metres, about 4 x 4 degrees around Gale crater).
Standard library only.
"""
import json
import os
import struct
import sys

W, H, PPD = 5760, 2880, 16          # from the .lbl file: LINE_SAMPLES, LINES, MAP_RESOLUTION
CENTER_LAT, CENTER_LON = -5.4, 137.8  # Gale crater centre (Mount Sharp area)
LANDING = (-4.5895, 137.4417)        # Curiosity landing site, Bradbury Landing (NASA)
SIZE = 64                            # 64 x 64 samples = 4 x 4 degrees at 16 px/degree

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gale_heightmap.js")


def main(path):
    data = open(path, "rb").read()
    if len(data) != W * H * 2:
        sys.exit(f"Unexpected file size {len(data)}; expected {W * H * 2} (16 px/deg MEGDR topography).")
    top_line = int(round((90 - CENTER_LAT) * PPD)) - SIZE // 2
    left_sample = int(round(CENTER_LON * PPD)) - SIZE // 2
    heights = []
    for r in range(SIZE):
        line = top_line + r
        for c in range(SIZE):
            s = left_sample + c
            heights.append(struct.unpack(">h", data[(line * W + s) * 2:(line * W + s) * 2 + 2])[0])
    lat_max = 90 - top_line / PPD
    lon_min = left_sample / PPD
    land_row = (90 - LANDING[0]) * PPD - top_line
    land_col = LANDING[1] * PPD - left_sample
    out = {
        "name": "Gale crater (Curiosity rover landing area), Mars",
        "size": SIZE, "pixels_per_degree": PPD,
        "lat_max": round(lat_max, 4), "lat_min": round(lat_max - SIZE / PPD, 4),
        "lon_min": round(lon_min, 4), "lon_max": round(lon_min + SIZE / PPD, 4),
        "unit": "metres relative to the Mars areoid",
        "min_m": min(heights), "max_m": max(heights),
        "landing_site": {"lat": LANDING[0], "lon": LANDING[1], "row": round(land_row, 2), "col": round(land_col, 2),
                         "height_m": heights[int(land_row) * SIZE + int(land_col)]},
        "heights": heights,
        "source": "NASA Mars Global Surveyor MOLA MEGDR, 16 px/degree (MGS-M-MOLA-5-MEGDR-L3-V1.0), NASA PDS Geosciences Node",
        "credit": "NASA / GSFC MOLA Science Team (D. E. Smith), Mars Global Surveyor; data via NASA PDS Geosciences Node",
        "url": "https://pds-geosciences.wustl.edu/mgs/mgs-m-mola-5-megdr-l3-v1/mgsl_300x/meg016/",
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by data/build_gale_heightmap.py from NASA MOLA data - do not edit by hand.\n")
        f.write("window.GALE_DEM = ")
        json.dump(out, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {OUT}: {SIZE}x{SIZE}, {out['min_m']}..{out['max_m']} m, landing site {out['landing_site']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
