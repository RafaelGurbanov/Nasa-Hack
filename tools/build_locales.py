"""
Build the game's text files from locales/en.json and locales/az.json.

  python tools/build_locales.py

- Checks that both languages have exactly the same keys and the same {placeholders}.
- Writes locales/locales.js (loaded with a <script> tag, so the game works from file:// offline).
- Writes docs/az-review.md: every Azerbaijani string next to the English one, for proofreading.
Standard library only. Exit code 1 if the two files do not match.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ["en", "az"]


def load(lang):
    with open(os.path.join(ROOT, "locales", f"{lang}.json"), encoding="utf-8") as f:
        return json.load(f)


def main():
    data = {lang: load(lang) for lang in LANGS}
    en, az = data["en"], data["az"]
    problems = []
    for k in sorted(set(en) ^ set(az)):
        problems.append(f"key only in {'en' if k in en else 'az'}: {k}")
    ph = lambda s: sorted(set(re.findall(r"\{(\w+)\}", s)))
    for k in sorted(set(en) & set(az)):
        if ph(en[k]) != ph(az[k]):
            problems.append(f"placeholders differ in {k}: en {ph(en[k])} vs az {ph(az[k])}")
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    with open(os.path.join(ROOT, "locales", "locales.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_locales.py from locales/en.json and locales/az.json - do not edit by hand.\n")
        f.write("window.LOCALES = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "az-review.md"), "w", encoding="utf-8") as f:
        f.write("# Azerbaijani text for proofreading\n\n")
        f.write(f"All {len(az)} strings of the game (generated from `locales/az.json`). "
                "Words in `{curly brackets}` are filled in by the game (numbers, dates, names); keep them as they are.\n\n")
        f.write("Fixed terms: sol, Həyat Təminatı, İstixana, Qalxan, Elm tapşırığı, alovlanma (flare), "
                "proton zərrəcikləri (SEP), mSv, «Yerdən mesaj».\n\n")
        f.write("| Key | English | Azərbaycanca |\n|---|---|---|\n")
        esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
        for k in en:
            f.write(f"| `{k}` | {esc(en[k])} | {esc(az[k])} |\n")
    print(f"ok: {len(en)} keys in each language; wrote locales/locales.js and docs/az-review.md")


if __name__ == "__main__":
    main()
